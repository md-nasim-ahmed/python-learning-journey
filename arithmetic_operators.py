""" Basic Arithmetic Operators """

a = 15
b = 4

print ("Addition:", a+b)
print("Subtraction:", a-b)
print("Multiplication:",a*b)
print("Division:", a/b)
print("Floor Division:", a//b)
print("Modulus:", a%b)
print("Exponentiation:", a**b)


"""
Operator Precedence

1) () — Parentheses
2) ** — Exponentiation
3) *, /, //, % — 
4) +, - — 

"""
result = 10 + 2 * 3 ** 2
print(result)