"""single, double, and multiple Python Strings"""

# Single Quote Strings('...')
single_str = 'Hello, Python!'
print(single_str)

quote = 'He said, "Python is awesome"'
print(quote)


# Double Quote Strings ("...")
double_str = "Hello, Python!"
print(double_str)

message = "It's a beautiful day for coding!"
print(message)


# Multiple Line Strings ('''...''' / """...""")
multiline_str = """ This is a multi-line string in Python.
You can write text across multiple lines
without using any newline(\\n) characters"""
print(multiline_str)

