""" String Split Case """

# split()
text = "Is It Case Conversion?"

words_list = text.split(" ")
print(words_list)


# lower().split()
text = "Is It Case Conversion?"

lower_list = text.lower().split()
print(lower_list)


# upper().split()
text = "Is It Case Conversion?"

upper_list = text.upper().split()
print(upper_list)

